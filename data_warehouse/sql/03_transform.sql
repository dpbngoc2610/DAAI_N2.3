INSERT INTO BRIDGE_SALES_PROMOTION (
    SALES_KEY, PROMOTION_KEY, PROMOTION_SEQUENCE, ALLOCATION_WEIGHT,
    SOURCE_BATCH_ID, ETL_LOADED_AT_UTC
)
WITH SOURCE_PROMOTIONS AS (
    SELECT F.SALES_KEY, I.BATCH_ID, I.PROMO_ID, 1 AS PROMOTION_SEQUENCE
    FROM FACT_SALES F
    JOIN STAGE.STG_ORDER_ITEMS I
      ON I.ORDER_ID = F.ORDER_ID AND I.SOURCE_ROW_NUMBER = F.SOURCE_ROW_NUMBER
    WHERE I.PROMO_ID IS NOT NULL
    UNION ALL
    SELECT F.SALES_KEY, I.BATCH_ID, I.PROMO_ID_2, 2 AS PROMOTION_SEQUENCE
    FROM FACT_SALES F
    JOIN STAGE.STG_ORDER_ITEMS I
      ON I.ORDER_ID = F.ORDER_ID AND I.SOURCE_ROW_NUMBER = F.SOURCE_ROW_NUMBER
    WHERE I.PROMO_ID_2 IS NOT NULL
    UNION ALL
    SELECT F.SALES_KEY, I.BATCH_ID, 'NO_PROMO', 0 AS PROMOTION_SEQUENCE
    FROM FACT_SALES F
    JOIN STAGE.STG_ORDER_ITEMS I
      ON I.ORDER_ID = F.ORDER_ID AND I.SOURCE_ROW_NUMBER = F.SOURCE_ROW_NUMBER
    WHERE I.PROMO_ID IS NULL AND I.PROMO_ID_2 IS NULL
), RESOLVED AS (
    SELECT S.SALES_KEY, P.PROMOTION_KEY, S.PROMOTION_SEQUENCE, S.BATCH_ID,
           COUNT(*) OVER (PARTITION BY S.SALES_KEY) AS PROMOTION_COUNT
    FROM SOURCE_PROMOTIONS S
    JOIN DIM_PROMOTION P ON P.PROMO_ID = S.PROMO_ID
)
SELECT SALES_KEY, PROMOTION_KEY, PROMOTION_SEQUENCE,
       ROUND(1.0 / PROMOTION_COUNT, 6), BATCH_ID,
       CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
FROM RESOLVED;

