INSERT INTO DIM_DATE (
    DATE_KEY, FULL_DATE, DAY_OF_MONTH, DAY_NAME, DAY_OF_WEEK, WEEK_OF_YEAR,
    MONTH_NUMBER, MONTH_NAME, QUARTER_NUMBER, YEAR_NUMBER, YEAR_MONTH, IS_WEEKEND
)
WITH ALL_DATES AS (
    SELECT ORDER_DATE AS D FROM STAGE.STG_ORDERS_ENRICHED
    UNION ALL SELECT SIGNUP_DATE FROM STAGE.STG_CUSTOMERS
    UNION ALL SELECT START_DATE FROM STAGE.STG_PROMOTIONS
    UNION ALL SELECT END_DATE FROM STAGE.STG_PROMOTIONS
    UNION ALL SELECT SNAPSHOT_DATE FROM STAGE.STG_INVENTORY
    UNION ALL SELECT RETURN_DATE FROM STAGE.STG_RETURNS
    UNION ALL SELECT REVIEW_DATE FROM STAGE.STG_REVIEWS
    UNION ALL SELECT SHIP_DATE FROM STAGE.STG_SHIPMENTS
    UNION ALL SELECT DELIVERY_DATE FROM STAGE.STG_SHIPMENTS
    UNION ALL SELECT JOIN_DATE FROM STAGE.STG_SHIPMENTS
    UNION ALL SELECT DATE FROM STAGE.STG_WEB_TRAFFIC
), BOUNDS AS (
    SELECT MIN(D) AS MIN_DATE, MAX(D) AS MAX_DATE FROM ALL_DATES WHERE D IS NOT NULL
), CALENDAR_CANDIDATES AS (
    SELECT DATEADD('DAY', SEQ4(), MIN_DATE)::DATE AS FULL_DATE, MAX_DATE
    FROM BOUNDS, TABLE(GENERATOR(ROWCOUNT => 20000))
)
SELECT TO_NUMBER(TO_CHAR(FULL_DATE, 'YYYYMMDD')), FULL_DATE, DAY(FULL_DATE),
       DAYNAME(FULL_DATE), DAYOFWEEKISO(FULL_DATE), WEEKISO(FULL_DATE),
       MONTH(FULL_DATE), MONTHNAME(FULL_DATE), QUARTER(FULL_DATE),
       YEAR(FULL_DATE), TO_CHAR(FULL_DATE, 'YYYY-MM'),
       DAYOFWEEKISO(FULL_DATE) IN (6, 7)
FROM CALENDAR_CANDIDATES
WHERE FULL_DATE <= MAX_DATE;

