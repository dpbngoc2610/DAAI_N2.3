INSERT INTO FACT_ORDERS (
    ORDER_KEY, ORDER_ID, ORDER_DATE_KEY, CUSTOMER_KEY, GEOGRAPHY_KEY,
    SALES_EMPLOYEE_KEY, SHIPPER_KEY, SHIP_DATE_KEY, DELIVERY_DATE_KEY,
    ORDER_STATUS, PAYMENT_METHOD, DEVICE_TYPE, ORDER_SOURCE, ORDER_COUNT,
    DELIVERED_ORDER_COUNT, RETURNED_ORDER_COUNT, ITEM_LINE_COUNT, TOTAL_QUANTITY,
    GROSS_SALES_AMOUNT, DISCOUNT_AMOUNT, NET_SALES_AMOUNT, COGS_AMOUNT,
    GROSS_PROFIT_AMOUNT, PAYMENT_VALUE, SHIPPING_FEE, REFUND_AMOUNT,
    NET_REVENUE_AFTER_RETURNS, DAYS_TO_SHIP, DAYS_TO_DELIVER, SOURCE_BATCH_ID,
    SOURCE_RECORD_HASH, ETL_LOADED_AT_UTC
)
WITH LINE_AGG AS (
    SELECT ORDER_ID, COUNT(*) AS ITEM_LINE_COUNT, SUM(QUANTITY) AS TOTAL_QUANTITY,
           SUM(GROSS_SALES_AMOUNT) AS GROSS_SALES_AMOUNT,
           SUM(DISCOUNT_AMOUNT) AS DISCOUNT_AMOUNT,
           SUM(NET_SALES_AMOUNT) AS NET_SALES_AMOUNT,
           SUM(COGS_AMOUNT) AS COGS_AMOUNT,
           SUM(GROSS_PROFIT_AMOUNT) AS GROSS_PROFIT_AMOUNT
    FROM FACT_SALES GROUP BY ORDER_ID
), RETURN_AGG AS (
    SELECT ORDER_ID, SUM(REFUND_AMOUNT) AS REFUND_AMOUNT
    FROM FACT_RETURNS GROUP BY ORDER_ID
)
SELECT ROW_NUMBER() OVER (ORDER BY O.ORDER_ID), O.ORDER_ID,
       TO_NUMBER(TO_CHAR(O.ORDER_DATE, 'YYYYMMDD')),
       COALESCE(C.CUSTOMER_KEY, 0), COALESCE(G.GEOGRAPHY_KEY, 0),
       COALESCE(E.SALES_EMPLOYEE_KEY, 0), COALESCE(FS.SHIPPER_KEY, 0),
       FS.SHIP_DATE_KEY, FS.DELIVERY_DATE_KEY, O.ORDER_STATUS, O.PAYMENT_METHOD,
       O.DEVICE_TYPE, O.ORDER_SOURCE, 1,
       IFF(LOWER(O.ORDER_STATUS) = 'delivered', 1, 0),
       IFF(R.REFUND_AMOUNT IS NULL, 0, 1),
       COALESCE(L.ITEM_LINE_COUNT, 0), COALESCE(L.TOTAL_QUANTITY, 0),
       ROUND(COALESCE(L.GROSS_SALES_AMOUNT, 0), 2),
       ROUND(COALESCE(L.DISCOUNT_AMOUNT, 0), 2),
       ROUND(COALESCE(L.NET_SALES_AMOUNT, 0), 2),
       ROUND(COALESCE(L.COGS_AMOUNT, 0), 2),
       ROUND(COALESCE(L.GROSS_PROFIT_AMOUNT, 0), 2),
       ROUND(COALESCE(FP.PAYMENT_VALUE, 0), 2),
       ROUND(COALESCE(FS.SHIPPING_FEE, 0), 2),
       ROUND(COALESCE(R.REFUND_AMOUNT, 0), 2),
       ROUND(COALESCE(L.NET_SALES_AMOUNT, 0) - COALESCE(R.REFUND_AMOUNT, 0), 2),
       FS.DAYS_TO_SHIP, FS.DAYS_TO_DELIVER, O.BATCH_ID, O.RECORD_HASH,
       CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
FROM STAGE.STG_ORDERS_ENRICHED O
LEFT JOIN DIM_CUSTOMER C ON C.CUSTOMER_ID = O.CUSTOMER_ID
LEFT JOIN DIM_GEOGRAPHY G ON G.ZIP = O.ZIP
LEFT JOIN DIM_SALES_EMPLOYEE E ON E.SALES_EMPLOYEE_ID = O.SALES_EMPLOYEE_ID
LEFT JOIN LINE_AGG L ON L.ORDER_ID = O.ORDER_ID
LEFT JOIN FACT_PAYMENTS FP ON FP.ORDER_ID = O.ORDER_ID
LEFT JOIN FACT_SHIPMENTS FS ON FS.ORDER_ID = O.ORDER_ID
LEFT JOIN RETURN_AGG R ON R.ORDER_ID = O.ORDER_ID;
